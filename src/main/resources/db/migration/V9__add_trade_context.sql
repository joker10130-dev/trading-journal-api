CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name VARCHAR(64) NOT NULL,
    category VARCHAR(16) NOT NULL,
    sentiment VARCHAR(8),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tags_id_user_unique UNIQUE (id, user_id),
    CONSTRAINT tags_category_check CHECK (category IN ('SETUP', 'MISTAKE', 'EMOTION', 'OTHER')),
    CONSTRAINT tags_sentiment_check CHECK (sentiment IS NULL OR sentiment IN ('POSITIVE', 'NEGATIVE', 'NEUTRAL')),
    CONSTRAINT tags_emotion_sentiment_check CHECK (category <> 'EMOTION' OR sentiment IS NOT NULL)
);

CREATE UNIQUE INDEX tags_user_name_lower_unique ON tags (user_id, lower(name));

CREATE TABLE trade_tag_mappings (
    trade_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    trading_account_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    PRIMARY KEY (trade_id, tag_id),
    CONSTRAINT trade_tag_mappings_trade_fk
        FOREIGN KEY (trade_id, trading_account_id, user_id)
            REFERENCES trades (id, trading_account_id, user_id) ON DELETE CASCADE,
    CONSTRAINT trade_tag_mappings_tag_fk
        FOREIGN KEY (tag_id, user_id) REFERENCES tags (id, user_id) ON DELETE CASCADE
);

CREATE INDEX trade_tag_mappings_tag_idx ON trade_tag_mappings (tag_id, user_id, trade_id);

CREATE TABLE trade_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id BIGINT NOT NULL UNIQUE,
    trading_account_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    text TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT trade_notes_trade_fk
        FOREIGN KEY (trade_id, trading_account_id, user_id)
            REFERENCES trades (id, trading_account_id, user_id) ON DELETE CASCADE
);

CREATE TABLE trade_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id BIGINT NOT NULL,
    trading_account_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    storage_key VARCHAR(64) NOT NULL UNIQUE,
    content_type VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT trade_images_trade_fk
        FOREIGN KEY (trade_id, trading_account_id, user_id)
            REFERENCES trades (id, trading_account_id, user_id) ON DELETE CASCADE,
    CONSTRAINT trade_images_content_type_check
        CHECK (content_type IN ('image/png', 'image/jpeg', 'image/webp'))
);

CREATE INDEX trade_images_trade_idx ON trade_images (trade_id, user_id, created_at);
