CREATE TABLE account_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    trading_account_id BIGINT NOT NULL,
    import_batch_id BIGINT NOT NULL,
    source VARCHAR(24) NOT NULL,
    source_fingerprint CHAR(64) NOT NULL,
    transaction_type VARCHAR(16) NOT NULL,
    occurred_at_server TIMESTAMP,
    amount NUMERIC(18, 5) NOT NULL,
    currency CHAR(3) NOT NULL,
    comment VARCHAR(512),
    CONSTRAINT account_transactions_batch_account_user_fk
        FOREIGN KEY (import_batch_id, trading_account_id, user_id)
            REFERENCES import_batches (id, trading_account_id, user_id),
    CONSTRAINT account_transactions_account_user_fk
        FOREIGN KEY (trading_account_id, user_id) REFERENCES trading_accounts (id, user_id),
    CONSTRAINT account_transactions_source_fingerprint_unique
        UNIQUE (trading_account_id, source_fingerprint),
    CONSTRAINT account_transactions_source_check CHECK (source IN ('TRADES_REPORT')),
    CONSTRAINT account_transactions_type_check
        CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'CREDIT'))
);
