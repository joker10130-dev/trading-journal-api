CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(100),
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Bangkok',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_lowercase CHECK (email = LOWER(email))
);

CREATE TABLE trading_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    name VARCHAR(120) NOT NULL,
    broker VARCHAR(120) NOT NULL,
    currency CHAR(3) NOT NULL,
    broker_login VARCHAR(64),
    trades_report_utc_offset_minutes SMALLINT,
    default_risk_mode VARCHAR(24),
    default_risk_value NUMERIC(18, 5),
    import_reminder_days SMALLINT NOT NULL DEFAULT 7,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT trading_accounts_user_name_unique UNIQUE (user_id, name),
    CONSTRAINT trading_accounts_id_user_unique UNIQUE (id, user_id),
    CONSTRAINT trading_accounts_currency_format CHECK (currency = UPPER(currency)),
    CONSTRAINT trading_accounts_risk_mode_check
        CHECK (default_risk_mode IS NULL OR default_risk_mode IN ('FIXED_AMOUNT', 'FIXED_STOP_DISTANCE')),
    CONSTRAINT trading_accounts_risk_value_check
        CHECK (default_risk_value IS NULL OR default_risk_value > 0),
    CONSTRAINT trading_accounts_reminder_days_check CHECK (import_reminder_days > 0)
);

CREATE TABLE import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    trading_account_id BIGINT NOT NULL,
    source VARCHAR(24) NOT NULL,
    filename VARCHAR(255) NOT NULL,
    file_sha256 CHAR(64) NOT NULL,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total_rows INTEGER NOT NULL,
    duplicate_rows INTEGER NOT NULL DEFAULT 0,
    imported_rows INTEGER NOT NULL DEFAULT 0,
    non_trade_rows INTEGER NOT NULL DEFAULT 0,
    error_rows INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT import_batches_account_user_fk
        FOREIGN KEY (trading_account_id, user_id) REFERENCES trading_accounts (id, user_id),
    CONSTRAINT import_batches_id_account_user_unique UNIQUE (id, trading_account_id, user_id),
    CONSTRAINT import_batches_source_check CHECK (source IN ('TRADINGVIEW', 'TRADES_REPORT')),
    CONSTRAINT import_batches_row_counts_check
        CHECK (total_rows >= 0 AND duplicate_rows >= 0 AND imported_rows >= 0
            AND non_trade_rows >= 0 AND error_rows >= 0)
);

CREATE TABLE trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    trading_account_id BIGINT NOT NULL,
    ticket VARCHAR(64) NOT NULL,
    symbol VARCHAR(32) NOT NULL,
    side VARCHAR(8) NOT NULL,
    status VARCHAR(24) NOT NULL,
    opened_at TIMESTAMPTZ,
    open_time_server TIMESTAMP,
    open_price NUMERIC(18, 5),
    opened_volume NUMERIC(18, 5),
    initial_sl_price NUMERIC(18, 5),
    risk_amount NUMERIC(18, 5),
    risk_source VARCHAR(24) NOT NULL DEFAULT 'NONE',
    r_multiple NUMERIC(18, 8),
    r_flag VARCHAR(32),
    gross_pnl NUMERIC(18, 5) NOT NULL DEFAULT 0,
    fees_and_swap NUMERIC(18, 5) NOT NULL DEFAULT 0,
    net_pnl NUMERIC(18, 5) NOT NULL DEFAULT 0,
    has_trades_report BOOLEAN NOT NULL DEFAULT FALSE,
    has_tradingview_data BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT trades_account_user_fk
        FOREIGN KEY (trading_account_id, user_id) REFERENCES trading_accounts (id, user_id),
    CONSTRAINT trades_account_ticket_unique UNIQUE (trading_account_id, ticket),
    CONSTRAINT trades_id_account_user_unique UNIQUE (id, trading_account_id, user_id),
    CONSTRAINT trades_side_check CHECK (side IN ('LONG', 'SHORT')),
    CONSTRAINT trades_status_check CHECK (status IN ('OPEN', 'PARTIALLY_CLOSED', 'CLOSED')),
    CONSTRAINT trades_risk_source_check
        CHECK (risk_source IN ('MANUAL', 'SL_ORDER', 'ACCOUNT_RULE', 'NONE')),
    CONSTRAINT trades_volume_positive CHECK (opened_volume IS NULL OR opened_volume > 0),
    CONSTRAINT trades_risk_positive CHECK (risk_amount IS NULL OR risk_amount > 0)
);

CREATE TABLE trade_closes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    trading_account_id BIGINT NOT NULL,
    trade_id BIGINT NOT NULL,
    import_batch_id BIGINT NOT NULL,
    source VARCHAR(24) NOT NULL,
    source_fingerprint CHAR(64) NOT NULL,
    volume NUMERIC(18, 5) NOT NULL,
    close_time_server TIMESTAMP,
    closed_at TIMESTAMPTZ,
    close_price NUMERIC(18, 5) NOT NULL,
    gross_pnl NUMERIC(18, 5) NOT NULL,
    swaps NUMERIC(18, 5) NOT NULL DEFAULT 0,
    commission NUMERIC(18, 5) NOT NULL DEFAULT 0,
    net_pnl NUMERIC(18, 5) NOT NULL,
    r_multiple NUMERIC(18, 8),
    CONSTRAINT trade_closes_trade_user_fk
        FOREIGN KEY (trade_id, trading_account_id, user_id)
            REFERENCES trades (id, trading_account_id, user_id),
    CONSTRAINT trade_closes_batch_account_user_fk
        FOREIGN KEY (import_batch_id, trading_account_id, user_id)
            REFERENCES import_batches (id, trading_account_id, user_id),
    CONSTRAINT trade_closes_source_fingerprint_unique UNIQUE (trade_id, source_fingerprint),
    CONSTRAINT trade_closes_source_check CHECK (source IN ('TRADINGVIEW', 'TRADES_REPORT')),
    CONSTRAINT trade_closes_volume_positive CHECK (volume > 0)
);

CREATE TABLE trade_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    trading_account_id BIGINT NOT NULL,
    import_batch_id BIGINT NOT NULL,
    trade_id BIGINT,
    external_order_id VARCHAR(64) NOT NULL,
    position_id VARCHAR(96),
    symbol VARCHAR(32),
    side VARCHAR(8),
    order_type VARCHAR(24),
    status VARCHAR(24) NOT NULL,
    volume NUMERIC(18, 5),
    update_time_server TIMESTAMP,
    updated_at TIMESTAMPTZ,
    order_price NUMERIC(18, 5),
    average_fill_price NUMERIC(18, 5),
    stop_price NUMERIC(18, 5),
    limit_price NUMERIC(18, 5),
    closed_pnl NUMERIC(18, 5),
    net_closed_pnl NUMERIC(18, 5),
    commission NUMERIC(18, 5),
    raw_row JSONB NOT NULL,
    CONSTRAINT trade_orders_batch_account_user_fk
        FOREIGN KEY (import_batch_id, trading_account_id, user_id)
            REFERENCES import_batches (id, trading_account_id, user_id),
    CONSTRAINT trade_orders_account_user_fk
        FOREIGN KEY (trading_account_id, user_id) REFERENCES trading_accounts (id, user_id),
    CONSTRAINT trade_orders_trade_user_fk
        FOREIGN KEY (trade_id, trading_account_id, user_id)
            REFERENCES trades (id, trading_account_id, user_id),
    CONSTRAINT trade_orders_account_external_id_unique UNIQUE (trading_account_id, external_order_id),
    CONSTRAINT trade_orders_side_check CHECK (side IS NULL OR side IN ('BUY', 'SELL'))
);

CREATE INDEX import_batches_account_imported_at_idx
    ON import_batches (trading_account_id, imported_at DESC);
CREATE INDEX trades_account_symbol_idx ON trades (trading_account_id, symbol);
CREATE INDEX trade_closes_user_closed_at_idx ON trade_closes (user_id, closed_at);
CREATE INDEX trade_orders_account_position_id_idx ON trade_orders (trading_account_id, position_id);
